"""Novikova et al. 2017 NLG human evaluation (EMNLP_17_submission, MIT): system outputs for dialogue acts (SFRES,
SFHOT, BAGEL; systems LOLS, WEN, Dusek) rated 1-6 on informativeness / naturalness / quality by three crowd workers
(gold = mean). Split by dialogue act (no act in two splits), filling fit / sel / test to ~400 outputs each (seed 0).
  python scripts/claude_prep_nlg.py -> results/claude_nlg/"""
import json, os
import numpy as np, pandas as pd

OUT = "results/claude_nlg"
A = ["informativeness", "naturalness", "quality"]
d = pd.read_csv("data/Novikova/emnlp_data_individual_hum_scores.csv")
g = d.groupby(["mr", "sys_ref", "dataset"])[A].mean().reset_index()
mrs = g.mr.unique()
perm = np.random.default_rng(0).permutation(len(mrs))
cnt = g.groupby("mr").size()
split_of, n, cur = {}, {"fit": 0, "sel": 0, "test": 0}, iter(("fit", "sel", "test"))
sp = next(cur)
for j in perm:
    if n[sp] >= 400:
        sp = next(cur, None)
        if sp is None:
            break
    split_of[mrs[j]] = sp; n[sp] += cnt[mrs[j]]
g["split"] = g.mr.map(split_of)
for x in ("chunks", "prompts", "out"):
    os.makedirs(f"{OUT}/{x}", exist_ok=True)
gold = []
for sp in ("fit", "sel", "test"):
    part = g[g.split == sp].sample(frac=1, random_state=0)
    with open(f"{OUT}/chunks/{sp}_00.jsonl", "w") as f:
        for i, (_, r) in enumerate(part.iterrows()):
            dom = {"SFHOT": "hotels", "SFRES": "restaurants", "BAGEL": "restaurants"}[r.dataset]
            u = f"## Domain: {dom}\n\n## Meaning representation:\n{r.mr}\n\n## Utterance:\n{str(r.sys_ref).strip()}\n\n## Your evaluation:"
            f.write(json.dumps({"id": f"{sp}{i:03d}", "user": u}, ensure_ascii=False) + "\n")
            w = len(str(r.sys_ref).split())
            gold.append(dict(id=f"{sp}{i:03d}", split=sp, **{a: float(r[a]) for a in A}, words=w, z=float(np.log1p(w))))
pd.DataFrame(gold).to_csv(f"{OUT}/gold.csv", index=False)
open(f"{OUT}/attrs.txt", "w").write("\n".join(A) + "\n")
open(f"{OUT}/format.txt", "w").write(
    "## Output format:\nThink briefly (at most a few sentences), then end your reply with exactly one line of JSON with an "
    "integer from 1 to 6 for each attribute:\n{" + ", ".join(f'"{a}": 1-6' for a in A) + "}\n")
open(f"{OUT}/prompts/v0.txt", "w").write("""You are a careful, calibrated evaluator. Your goal is to produce an accurate evaluation by following the Instructions below.

## Task
Evaluate the Utterance, generated by a dialogue system to express the Meaning representation, using the Instructions below.
1. Consider every strength and flaw you find when making your evaluation.
2. Based on the number and severity of the strengths and flaws, assign a value.

## Instructions:
- informativeness: Evaluate whether the utterance provides all the useful information from the meaning representation. Rate from 1 to 6.
- naturalness: Evaluate whether the utterance could have been produced by a native speaker. Rate from 1 to 6.
- quality: Evaluate how you judge the overall quality of the utterance in terms of its grammatical correctness and fluency. Rate from 1 to 6.
""")
G = pd.DataFrame(gold)
print(G.split.value_counts().to_dict(), "mean words", round(G.words.mean(), 1))
print(G[A].corr("spearman").round(2))
